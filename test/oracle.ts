/** Skyfield fixtures generated by `oracle/positions.py`. */
export const oracle = fixture;

/** Skyfield Pass fixtures generated by `oracle/passes.py`. */
export const passOracle = passesFixture;

/** The Elements of one fixture set, read from the OMM object the Oracle wrote; the fixture's own records name sets by key. */
export function fixtureElements(key: string): Elements {
  const set = (fixture.elements as Record<string, { omm: unknown } | undefined>)[key];
  if (set === undefined) throw new Error(`The fixture has no Elements set "${key}"`);
  return readElements(set.omm);
}

/**
 * Degrees along the ground between two sub-points, by the haversine formula
 * written out here rather than by the Engine's own: a track's shape is
 * measured against an independent formula, not against the one
 * `ground-track.ts` samples with.
 */
export function haversineDegrees(from: GroundPoint, to: GroundPoint): number {
  const half = (degrees: number) => Math.sin((degrees * Math.PI) / 360) ** 2;
  const latitudes = Math.cos((from.latitude * Math.PI) / 180) * Math.cos((to.latitude * Math.PI) / 180);
  const chord = Math.sqrt(half(to.latitude - from.latitude) + latitudes * half(to.longitude - from.longitude));
  return (2 * Math.asin(Math.min(1, chord)) * 180) / Math.PI;
}

/** The greatest separation between neighbouring points of a track, in degrees: how coarsely its worst stretch is drawn. */
export const worstGapDegrees = (track: readonly TrackPoint[]) =>
  Math.max(...track.slice(1).map((point, index) => haversineDegrees(track[index]!, point)));

const KM_PER_DEGREE = 111.195;

/**
 * Distance in kilometres between two Positions, treating the small
 * latitude, longitude and altitude differences as orthogonal.
 */
export function positionDistanceKm(a: Position, b: Position): number {
  const meanLatitude = ((a.latitude + b.latitude) / 2) * (Math.PI / 180);
  let longitudeDelta = Math.abs(a.longitude - b.longitude);
  if (longitudeDelta > 180) longitudeDelta = 360 - longitudeDelta;
  const north = (a.latitude - b.latitude) * KM_PER_DEGREE;
  const east = longitudeDelta * KM_PER_DEGREE * Math.cos(meanLatitude);
  const up = a.altitude - b.altitude;
  return Math.hypot(north, east, up);
}

